//! Generates the C glue between QuickJS and the native functions: one guarded
//! entry stub per function, plus the `tsaot:native` C module exporting
//! `__tsaot_bind`, which wraps each interpreted fallback in its stub.

use std::fmt::Write;

use tsaot_front::erase::{BIND_FN, NATIVE_MODULE};
use tsaot_front::ir::{self, Ty};

/// C init function name passed to `qjsc -M tsaot:native,<CNAME>`.
pub const MODULE_CNAME: &str = "tsaot";

fn c_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "double",
        Ty::Bool => "bool",
        Ty::Void => "void",
    }
}

/// A C string literal; octal escapes for anything outside printable ASCII.
fn c_str(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' | b'\\' => write!(out, "\\{}", b as char).unwrap(),
            0x20..=0x7e => out.push(b as char),
            _ => write!(out, "\\{b:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}

pub fn generate(m: &ir::Module) -> String {
    let mut c = String::new();
    c.push_str("/* Generated by tsaot. */\n#include \"tsaot_rt.h\"\n\n");

    for (i, f) in m.funcs.iter().enumerate() {
        let params: Vec<&str> = f.params.iter().map(|&t| c_ty(t)).collect();
        let params = if params.is_empty() { "void".to_string() } else { params.join(", ") };
        writeln!(c, "extern {} tsaot_fn_{i}({params});", c_ty(f.ret)).unwrap();
    }
    c.push('\n');

    for (i, f) in m.funcs.iter().enumerate() {
        writeln!(c, "/* {} */", f.name.replace("*/", "* /")).unwrap();
        writeln!(
            c,
            "static JSValue tsaot_entry_{i}(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv, int magic, JSValueConst *data)\n{{"
        )
        .unwrap();
        for (j, &t) in f.params.iter().enumerate() {
            writeln!(c, "    {} a{j};", c_ty(t)).unwrap();
        }
        // Guard: exact argument types, or fall back to the interpreter.
        let mut guard = vec![format!("argc < {}", f.params.len())];
        for (j, &t) in f.params.iter().enumerate() {
            let conv = if t == Ty::Bool { "tsaot_arg_bool" } else { "tsaot_arg_f64" };
            guard.push(format!("!{conv}(argv[{j}], &a{j})"));
        }
        if !f.params.is_empty() {
            writeln!(c, "    if ({})\n        return JS_Call(ctx, data[0], this_val, argc, argv);", guard.join(" || "))
                .unwrap();
        }
        let args: Vec<String> = (0..f.params.len()).map(|j| format!("a{j}")).collect();
        let call = format!("tsaot_fn_{i}({})", args.join(", "));
        c.push_str("    tsaot_enter();\n");
        match f.ret {
            Ty::Void => writeln!(c, "    {call};").unwrap(),
            t => writeln!(c, "    {} r = {call};", c_ty(t)).unwrap(),
        }
        c.push_str(
            "    if (tsaot_leave())\n        return JS_ThrowRangeError(ctx, \"Maximum call stack size exceeded\");\n",
        );
        match f.ret {
            Ty::Void => c.push_str("    return JS_UNDEFINED;\n"),
            Ty::Bool => c.push_str("    return JS_NewBool(ctx, r);\n"),
            Ty::F64 => c.push_str("    return tsaot_ret_f64(ctx, r);\n"),
        }
        c.push_str("}\n\n");
    }

    let n = m.funcs.len();
    c.push_str("static const struct { JSCFunctionData *fn; const char *name; int length; } tsaot_table[] = {\n");
    for (i, f) in m.funcs.iter().enumerate() {
        writeln!(c, "    {{ tsaot_entry_{i}, {}, {} }},", c_str(&f.name), f.params.len()).unwrap();
    }
    c.push_str("};\n\n");

    write!(
        c,
        r#"static JSValue tsaot_bind(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    JSValue arr = JS_NewArray(ctx);
    if (JS_IsException(arr))
        return arr;
    for (int i = 0; i < {n}; i++) {{
        if (i >= argc || !JS_IsFunction(ctx, argv[i])) {{
            JS_FreeValue(ctx, arr);
            return JS_ThrowTypeError(ctx, "{BIND_FN}: expected fallback function");
        }}
        JSValue f = JS_NewCFunctionData2(ctx, tsaot_table[i].fn, tsaot_table[i].name,
                                         tsaot_table[i].length, 0, 1, &argv[i]);
        if (JS_IsException(f) || JS_SetPropertyUint32(ctx, arr, i, f) < 0) {{
            JS_FreeValue(ctx, arr);
            return JS_EXCEPTION;
        }}
    }}
    return arr;
}}

static int tsaot_module_init(JSContext *ctx, JSModuleDef *m)
{{
    return JS_SetModuleExport(ctx, m, "{BIND_FN}",
                              JS_NewCFunction(ctx, tsaot_bind, "{BIND_FN}", {n}));
}}

/* Registered as "{NATIVE_MODULE}". */
JSModuleDef *js_init_module_{MODULE_CNAME}(JSContext *ctx, const char *name)
{{
    JSModuleDef *m = JS_NewCModule(ctx, name, tsaot_module_init);
    if (!m)
        return NULL;
    JS_AddModuleExport(ctx, m, "{BIND_FN}");
    return m;
}}
"#
    )
    .unwrap();
    c
}
