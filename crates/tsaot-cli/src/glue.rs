//! Generates the C glue between QuickJS and the native functions: the
//! `tsaot:native` C module exporting `__tsaot_bind(i, fallback)`, which
//! creates the JS function object for native function `i`.
//!
//! The JS entry itself (`tsaot_fast_<i>`) is Cranelift code: the engine's
//! `JSCFunctionFast` hook calls it straight from the interpreter's call
//! opcodes. When it declines (ill-typed arguments), the engine calls the
//! regular C function, a shared trampoline into the interpreted fallback.

use std::fmt::Write;

use tsaot_codegen::{NATIVE_STACK_BUDGET, jsvalue, layout};
use tsaot_front::ClassDecl;
use tsaot_front::erase::{BIND_FN, CELLS_OBJ, CLASS_FN, INIT_FN, METHOD_FN, NATIVE_MODULE};
use tsaot_front::ir;

/// C init function name passed to `qjsc -M tsaot:native,<CNAME>`.
pub const MODULE_CNAME: &str = "tsaot";

/// A C string literal; octal escapes for anything outside printable ASCII.
fn c_str(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' | b'\\' => write!(out, "\\{}", b as char).unwrap(),
            0x20..=0x7e => out.push(b as char),
            _ => write!(out, "\\{b:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}

pub fn generate(m: &ir::Module, mutable: &[usize], classes: &[ClassDecl]) -> String {
    let mut c = String::new();
    write!(
        c,
        r#"/* Generated by tsaot. */
#include <stddef.h>
#include "tsaot_rt.h"

/* The Cranelift entries read and write JSValues directly. */
_Static_assert(sizeof(JSValue) == {size}, "tsaot needs the 64-bit struct JSValue layout");
_Static_assert(offsetof(JSValue, tag) == {tag_off}, "unexpected JSValue layout");
_Static_assert(JS_TAG_INT == {int} && JS_TAG_BOOL == {bool} && JS_TAG_UNDEFINED == {undef} &&
               JS_TAG_UNINITIALIZED == {uninit} && JS_TAG_EXCEPTION == {exc} &&
               JS_TAG_FLOAT64 == {f64} && JS_TAG_STRING == {string} && JS_TAG_NULL == {null},
               "unexpected JSValue tags");
_Static_assert(JS_BINOP_ADD == 0 && JS_BINOP_XOR == 11 && JS_BINOP_LT == 12 && JS_BINOP_INSTANCEOF == 21 &&
               JS_UNOP_NEG == 0 && JS_UNOP_TYPEOF == 6, "unexpected operator numbering");
_Static_assert(TSAOT_NATIVE_STACK == {budget}u, "stack budget mismatch");

"#,
        size = jsvalue::SIZE,
        tag_off = jsvalue::TAG_OFFSET,
        int = jsvalue::TAG_INT,
        bool = jsvalue::TAG_BOOL,
        undef = jsvalue::TAG_UNDEFINED,
        uninit = jsvalue::TAG_UNINITIALIZED,
        exc = jsvalue::TAG_EXCEPTION,
        f64 = jsvalue::TAG_FLOAT64,
        string = jsvalue::TAG_STRING,
        null = jsvalue::TAG_NULL,
        budget = NATIVE_STACK_BUDGET,
    )
    .unwrap();
    for (name, v) in layout::ALL {
        writeln!(c, "_Static_assert(JS_LAYOUT_{name} == {v}, \"engine layout mismatch\");").unwrap();
    }
    c.push('\n');

    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        writeln!(c, "extern JSCFunctionFast tsaot_fast_{i}; /* {} */", f.name.replace("*/", "* /")).unwrap();
    }

    let n = m.funcs.len();
    let nclasses = m.homes / 2;
    let nall = n + m.closures.len();
    // Trailing sentinels keep arrays non-empty.
    // kind: 0 plain, 1 async, 2 generator, 3 async generator (see
    // tsaot_function_kind).
    c.push_str(
        "\nstatic const struct { JSCFunctionFast *fast; const char *name; int length, kind; } tsaot_table[] = {\n",
    );
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        let kind = match (f.is_generator, f.is_async) {
            (true, true) => 3,
            (true, false) => 2,
            (false, a) => a as u8,
        };
        writeln!(c, "    {{ tsaot_fast_{i}, {}, {}, {kind} }},", c_str(&f.name), f.js_length).unwrap();
    }
    c.push_str("    { NULL, NULL, 0, 0 },\n};\n\n");
    writeln!(c, "TsaotFnCache tsaot_fn_caches[{}];\nconst int32_t tsaot_nfn_caches = {nall};\n", nall + 1).unwrap();

    // Step functions of async functions and generators.
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        if f.is_async || f.is_generator {
            writeln!(c, "extern TsaotStep tsaot_fn_{i};").unwrap();
        }
    }
    c.push_str("TsaotStep *const tsaot_steps[] = {\n");
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        if f.is_async || f.is_generator {
            writeln!(c, "    tsaot_fn_{i},").unwrap();
        } else {
            c.push_str("    NULL,\n");
        }
    }
    c.push_str("    NULL,\n};\n\n");

    // Module state tables.
    let list = |items: Vec<String>| -> String {
        let mut s: String = items.into_iter().map(|i| format!("    {i},\n")).collect();
        s.push_str("    0\n");
        s
    };
    let (ncells, nstrings, natoms) = (m.cells.len(), m.strings.len(), m.atoms.len());
    writeln!(c, "JSValue tsaot_cells[{}];", ncells + 1).unwrap();
    writeln!(c, "JSValue tsaot_strings[{}];", nstrings + 1).unwrap();
    writeln!(c, "JSAtom tsaot_atoms[{}];", natoms + 1).unwrap();
    writeln!(
        c,
        "const int tsaot_ncells = {ncells}, tsaot_nstrings = {nstrings}, tsaot_natoms = {natoms}, tsaot_nmutable = {};",
        mutable.len()
    )
    .unwrap();
    write!(c, "const char *const tsaot_cell_names[] = {{\n{}}};\n", list(m.cells.iter().map(|s| c_str(s)).collect()))
        .unwrap();
    write!(c, "const char *const tsaot_atom_names[] = {{\n{}}};\n", list(m.atoms.iter().map(|s| c_str(s)).collect()))
        .unwrap();
    write!(
        c,
        "const char *const tsaot_string_data[] = {{\n{}}};\n",
        list(m.strings.iter().map(|s| c_str(s)).collect())
    )
    .unwrap();
    write!(
        c,
        "const size_t tsaot_string_lens[] = {{\n{}}};\n",
        list(m.strings.iter().map(|s| s.len().to_string()).collect())
    )
    .unwrap();
    write!(c, "const int tsaot_mutable_cells[] = {{\n{}}};\n\n", list(mutable.iter().map(|k| k.to_string()).collect()))
        .unwrap();

    // Classes: private name values and home objects, and what each class
    // hands over.
    writeln!(c, "JSValue tsaot_privates[{}];", m.privates + 1).unwrap();
    writeln!(c, "JSValue tsaot_homes[{}];", m.homes + 1).unwrap();
    writeln!(c, "const int tsaot_nprivates = {}, tsaot_nhomes = {};", m.privates, m.homes).unwrap();
    c.push_str("struct tsaot_class_var { const char *name; int slot; };\n");
    for cl in classes {
        writeln!(c, "static const struct tsaot_class_var tsaot_class_vars_{}[] = {{", cl.index).unwrap();
        for (name, slot) in &cl.vars {
            writeln!(c, "    {{ {}, {slot} }},", c_str(name)).unwrap();
        }
        c.push_str("    { NULL, 0 },\n};\n");
    }
    writeln!(c, "static const struct tsaot_class_var *const tsaot_class_vars[{}] = {{", m.homes / 2 + 1).unwrap();
    for cl in classes {
        writeln!(c, "    [{0}] = tsaot_class_vars_{0},", cl.index).unwrap();
    }
    c.push_str("};\n\n");

    write!(
        c,
        r#"/* Slow path, taken when a fast entry declines: the interpreted fallback. */
static JSValue tsaot_fallback(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                              int magic, JSValueConst *data)
{{
    return JS_Call(ctx, data[0], this_val, argc, argv);
}}

/* {BIND_FN}(i, fallback): the JS function object of native function i. */
static JSValue tsaot_bind(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t i;
    if (argc < 2 || JS_VALUE_GET_TAG(argv[0]) != JS_TAG_INT || !JS_IsFunction(ctx, argv[1]))
        return JS_ThrowTypeError(ctx, "{BIND_FN}: expected (index, fallback)");
    i = JS_VALUE_GET_INT(argv[0]);
    if (i < 0 || i >= {n})
        return JS_ThrowRangeError(ctx, "{BIND_FN}: bad index");
    return tsaot_function_kind(ctx, JS_NewCFunctionDataFast(ctx, tsaot_table[i].fast, tsaot_fallback,
                                                            tsaot_table[i].name, tsaot_table[i].length, 0,
                                                            1, &argv[1]),
                               argv[1], tsaot_table[i].kind);
}}

/* Closures never decline (all their parameters are JS values), but if the
 * engine calls their regular function anyway, go to the native entry. */
static JSValue tsaot_closure_slow(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                                  int magic, JSValueConst *data)
{{
    return tsaot_table[magic].fast(ctx, this_val, argc, argv, data);
}}

/* A closure of native function `fn` over `data` (borrowed). */
JSValue tsaot_make_closure(JSContext *ctx, int fn, int n, JSValue *data)
{{
    return tsaot_function_kind(ctx, tsaot_new_closure(ctx, &tsaot_fn_caches[fn], tsaot_table[fn].fast,
                                                      tsaot_closure_slow, tsaot_table[fn].name,
                                                      tsaot_table[fn].length, fn, n, data),
                               JS_UNDEFINED, tsaot_table[fn].kind);
}}

/* {METHOD_FN}(i, Class, is_static, key, accessor): replace a class method
 * (accessor 0), getter (1) or setter (2) with native function i; the
 * interpreted one becomes its fallback. A method keeps the attributes of a
 * class method (writable, configurable, not enumerable); an accessor only
 * has its getter or setter replaced. */
static JSValue tsaot_method(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t i, is_static, accessor = 0;
    JSValue holder, fallback, stub;
    JSPropertyDescriptor desc;
    JSAtom key;
    int r;
    if (argc < 4 || JS_ToInt32(ctx, &i, argv[0]) || JS_ToInt32(ctx, &is_static, argv[2]) ||
        (argc > 4 && JS_ToInt32(ctx, &accessor, argv[4])) || i < 0 || i >= {nall})
        return JS_ThrowTypeError(ctx, "{METHOD_FN}: bad arguments");
    holder = is_static ? JS_DupValue(ctx, argv[1]) : JS_GetPropertyStr(ctx, argv[1], "prototype");
    if (JS_IsException(holder))
        return holder;
    key = JS_ValueToAtom(ctx, argv[3]);
    if (key == JS_ATOM_NULL) {{
        JS_FreeValue(ctx, holder);
        return JS_EXCEPTION;
    }}
    if (accessor) {{
        r = JS_GetOwnProperty(ctx, &desc, holder, key);
        fallback = JS_UNDEFINED;
        if (r > 0) {{
            fallback = JS_DupValue(ctx, accessor == 1 ? desc.getter : desc.setter);
            JS_FreeValue(ctx, desc.value);
            JS_FreeValue(ctx, desc.getter);
            JS_FreeValue(ctx, desc.setter);
        }} else if (r < 0) {{
            fallback = JS_EXCEPTION;
        }}
    }} else {{
        fallback = JS_GetProperty(ctx, holder, key);
    }}
    if (JS_IsException(fallback) || !JS_IsFunction(ctx, fallback)) {{
        JS_FreeValue(ctx, fallback);
        JS_FreeValue(ctx, holder);
        JS_FreeAtom(ctx, key);
        return JS_ThrowTypeError(ctx, "{METHOD_FN}: not a method");
    }}
    stub = tsaot_function_kind(ctx, JS_NewCFunctionDataFast(ctx, tsaot_table[i].fast, tsaot_fallback,
                                                            tsaot_table[i].name, tsaot_table[i].length, 0,
                                                            1, &fallback),
                               fallback, tsaot_table[i].kind);
    JS_FreeValue(ctx, fallback);
    if (JS_IsException(stub)) {{
        r = -1;
    }} else if (accessor) {{
        r = JS_DefineProperty(ctx, holder, key, JS_UNDEFINED, accessor == 1 ? stub : JS_UNDEFINED,
                              accessor == 2 ? stub : JS_UNDEFINED,
                              (accessor == 1 ? JS_PROP_HAS_GET : JS_PROP_HAS_SET) | JS_PROP_THROW);
        JS_FreeValue(ctx, stub);
    }} else {{
        r = JS_DefinePropertyValue(ctx, holder, key, stub, JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE | JS_PROP_THROW);
    }}
    JS_FreeValue(ctx, holder);
    JS_FreeAtom(ctx, key);
    return r < 0 ? JS_EXCEPTION : JS_UNDEFINED;
}}

/* {CLASS_FN}(k, Class, fn) in a static block of class k: its home objects,
 * and the values of the private names that `fn` references. */
static JSValue tsaot_class(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t k;
    const struct tsaot_class_var *v;
    JSValue proto;
    if (argc < 3 || JS_ToInt32(ctx, &k, argv[0]) || k < 0 || k >= {nclasses} || !tsaot_class_vars[k])
        return JS_ThrowTypeError(ctx, "{CLASS_FN}: bad arguments");
    proto = JS_GetPropertyStr(ctx, argv[1], "prototype");
    if (JS_IsException(proto))
        return proto;
    JS_FreeValue(ctx, tsaot_homes[2 * k]);
    JS_FreeValue(ctx, tsaot_homes[2 * k + 1]);
    tsaot_homes[2 * k] = proto;
    tsaot_homes[2 * k + 1] = JS_DupValue(ctx, argv[1]);
    for (v = tsaot_class_vars[k]; v->name; v++) {{
        JSAtom name = JS_NewAtom(ctx, v->name);
        JSValue val;
        if (name == JS_ATOM_NULL)
            return JS_EXCEPTION;
        if (JS_GetClosureVariable(ctx, argv[2], name, &val)) {{
            JS_FreeValue(ctx, tsaot_privates[v->slot]);
            tsaot_privates[v->slot] = val;
        }}
        JS_FreeAtom(ctx, name);
    }}
    return JS_UNDEFINED;
}}

static JSValue tsaot_exports[4];

static int tsaot_module_init(JSContext *ctx, JSModuleDef *m)
{{
    if (JS_SetModuleExport(ctx, m, "{BIND_FN}",
                           JS_NewCFunction(ctx, tsaot_bind, "{BIND_FN}", 2)) < 0)
        return -1;
    /* The module owns the state object: its finalizer releases the cells. */
    if (JS_SetModuleExport(ctx, m, "__tsaot_state", tsaot_exports[0]) < 0 ||
        JS_SetModuleExport(ctx, m, "{INIT_FN}", tsaot_exports[1]) < 0 ||
        JS_SetModuleExport(ctx, m, "{CELLS_OBJ}", tsaot_exports[2]) < 0 ||
        JS_SetModuleExport(ctx, m, "{METHOD_FN}",
                           JS_NewCFunction(ctx, tsaot_method, "{METHOD_FN}", 5)) < 0)
        return -1;
    if (JS_SetModuleExport(ctx, m, "{CLASS_FN}", JS_NewCFunction(ctx, tsaot_class, "{CLASS_FN}", 3)) < 0)
        return -1;
    return 0;
}}

/* Registered as "{NATIVE_MODULE}"; called while the context is created,
 * before any JS runs. */
JSModuleDef *js_init_module_{MODULE_CNAME}(JSContext *ctx, const char *name)
{{
    JSModuleDef *m;
    if (tsaot_runtime_init(ctx, &tsaot_exports[0], &tsaot_exports[1], &tsaot_exports[2]) < 0)
        return NULL;
    m = JS_NewCModule(ctx, name, tsaot_module_init);
    if (!m)
        return NULL;
    JS_AddModuleExport(ctx, m, "{BIND_FN}");
    JS_AddModuleExport(ctx, m, "__tsaot_state");
    JS_AddModuleExport(ctx, m, "{INIT_FN}");
    JS_AddModuleExport(ctx, m, "{CELLS_OBJ}");
    JS_AddModuleExport(ctx, m, "{METHOD_FN}");
    JS_AddModuleExport(ctx, m, "{CLASS_FN}");
    return m;
}}
"#
    )
    .unwrap();
    c
}
