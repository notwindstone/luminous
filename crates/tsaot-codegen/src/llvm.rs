//! The LLVM backend: translates the backend-neutral IR (`mir.rs`) to LLVM IR
//! (text), which `clang -O3` compiles to an object file.
//!
//! The translation keeps the IR's semantics (Cranelift's) where LLVM's
//! differ: shift amounts are masked, `srem` by -1 cannot overflow,
//! float-to-int conversions saturate (`llvm.fptosi.sat`), and `fmin` /
//! `fmax` are `llvm.minimum` / `llvm.maximum`. Variables become allocas,
//! which mem2reg turns into SSA values. Booleans are `i8`s, with an `i1`
//! twin (`%vN.b`) for comparison results.
//!
//! Addresses are `i64`s in the IR. Each value used as an address also gets
//! a `ptr` twin (`%vN.p`): a global (`@tsaot_cells`), a stack slot, a
//! `getelementptr` from another address, a pointer loaded as one, or an
//! `inttoptr`. Address arithmetic on known bases thus stays visible to
//! LLVM's alias analysis.
//!
//! The functions only native code calls (`tsaot_fn_<i>`) are internal:
//! LLVM may inline them, specialize their calling convention, or drop them.

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::OnceLock;

use anyhow::{Context, Result, bail};

use crate::mir::{
    self, ArgExt, BinOp, Block, ConvOp, DataInit, FloatCC, InstData, IntCC, Linkage, Region, Signature, Type, UnOp,
    Value,
};

#[derive(Clone, Debug)]
pub struct Options {
    /// The clang that compiles the LLVM IR.
    pub clang: PathBuf,
    /// Optimization level, as clang's `-O`.
    pub opt_level: String,
    /// The CPU to compile for, as clang's `-march` (default: the host's).
    pub march: String,
}

impl Default for Options {
    fn default() -> Self {
        Options { clang: "clang".into(), opt_level: "3".into(), march: "native".into() }
    }
}

/// The data layout and triple of clang's default target.
fn target(clang: &Path) -> Result<&'static (String, String)> {
    static TARGET: OnceLock<(String, String)> = OnceLock::new();
    if let Some(t) = TARGET.get() {
        return Ok(t);
    }
    let out = Command::new(clang)
        .args(["-S", "-emit-llvm", "-x", "c", "-o", "-", "-"])
        .stdin(std::process::Stdio::null())
        .output()
        .with_context(|| format!("running {} (the LLVM backend needs clang)", clang.display()))?;
    if !out.status.success() {
        bail!("{} failed: {}", clang.display(), String::from_utf8_lossy(&out.stderr));
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let find = |key: &str| {
        text.lines()
            .find_map(|l| l.strip_prefix(key))
            .map(|v| v.trim().trim_matches('"').to_string())
            .unwrap_or_default()
    };
    let (layout, triple) = (find("target datalayout = "), find("target triple = "));
    if triple.is_empty() {
        bail!("cannot determine clang's target");
    }
    Ok(TARGET.get_or_init(|| (layout, triple)))
}

/// Compile the LLVM IR in `ll` to the object file `obj` for the host CPU.
pub fn compile(ll: &Path, obj: &Path, opts: &Options) -> Result<()> {
    let mut cmd = Command::new(&opts.clang);
    cmd.arg(format!("-O{}", opts.opt_level)).arg(format!("-march={}", opts.march));
    cmd.args(["-c", "-Wno-override-module"]);
    if target(&opts.clang)?.1.starts_with("x86_64") {
        // Moving values to AVX-512 mask registers saves little and takes
        // time quadratic in the size of a function.
        cmd.args(["-mllvm", "-disable-x86-domain-reassignment"]);
    }
    let out = cmd
        .arg(ll)
        .arg("-o")
        .arg(obj)
        .output()
        .with_context(|| format!("running {} (the LLVM backend needs clang)", opts.clang.display()))?;
    if !out.status.success() {
        bail!("{} failed on {}:\n{}", opts.clang.display(), ll.display(), String::from_utf8_lossy(&out.stderr));
    }
    Ok(())
}

/// LLVM IR for module `m`.
pub fn emit(m: &mir::Module, opts: &Options) -> Result<String> {
    let (layout, triple) = target(&opts.clang)?;
    let sp_register = if triple.starts_with("x86_64") {
        "rsp"
    } else if triple.starts_with("aarch64") || triple.starts_with("arm64") {
        "sp"
    } else {
        bail!("the LLVM backend does not support the target {triple}")
    };
    let mut out = String::new();
    writeln!(out, "; Generated by tsaot.\nsource_filename = \"tsaot\"").unwrap();
    if !layout.is_empty() {
        writeln!(out, "target datalayout = \"{layout}\"").unwrap();
    }
    writeln!(out, "target triple = \"{triple}\"\n").unwrap();

    for d in &m.data {
        let constness = if d.writable { "global" } else { "constant" };
        match &d.init {
            None => writeln!(out, "@{} = external dso_local global [0 x i8]", d.name).unwrap(),
            Some(DataInit::Zeroed { size }) => {
                let linkage = if d.linkage == Linkage::Local { "internal " } else { "" };
                writeln!(
                    out,
                    "@{} = {linkage}dso_local {constness} [{size} x i8] zeroinitializer, align {}",
                    d.name, d.align
                )
                .unwrap()
            }
            Some(DataInit::Bytes(bytes)) => {
                let linkage = if d.linkage == Linkage::Local { "internal " } else { "" };
                let mut lit = String::new();
                for b in bytes {
                    write!(lit, "\\{b:02X}").unwrap();
                }
                writeln!(
                    out,
                    "@{} = {linkage}dso_local {constness} [{} x i8] c\"{lit}\", align {}",
                    d.name,
                    bytes.len(),
                    d.align
                )
                .unwrap()
            }
        }
    }
    out.push('\n');

    let mut intrinsics = BTreeSet::new();
    for f in &m.funcs {
        match &f.body {
            None => {
                writeln!(out, "declare dso_local {} @{}({}) #0", ret_type(&f.sig), f.name, param_types(&f.sig))
                    .unwrap();
            }
            Some(body) => {
                let mut e = FnEmitter::new(m, body, &mut intrinsics);
                let text = e.function(&f.name, f.linkage);
                out.push_str(&text);
            }
        }
    }
    out.push('\n');
    for i in &intrinsics {
        writeln!(out, "{i}").unwrap();
    }
    writeln!(out, "\nattributes #0 = {{ nounwind }}").unwrap();
    writeln!(out, "attributes #1 = {{ nounwind }}").unwrap();
    // No vectorization in huge functions and async step functions: the SLP
    // vectorizer's time grows too fast with their size, for little gain.
    writeln!(out, "attributes #2 = {{ nounwind noimplicitfloat }}").unwrap();
    writeln!(out, "\n!0 = !{{!\"{sp_register}\"}}").unwrap();
    writeln!(out, "!1 = !{{!\"branch_weights\", i32 1, i32 2000}}").unwrap();
    writeln!(out, "!2 = !{{!\"branch_weights\", i32 2000, i32 1}}").unwrap();
    writeln!(out, "!3 = !{{}}").unwrap();
    // Type-based alias analysis: one scalar type per region, under a root
    // of its own (unrelated to C's, if C code is ever linked in).
    writeln!(out, "!4 = !{{!\"tsaot regions\"}}").unwrap();
    for (k, r) in Region::ALL.iter().enumerate() {
        let ty = 5 + 2 * k;
        writeln!(out, "!{ty} = !{{!\"{r:?}\", !4, i64 0}}").unwrap();
        writeln!(out, "!{} = !{{!{ty}, !{ty}, i64 0}}", ty + 1).unwrap();
    }
    Ok(out)
}

/// The metadata of an access to `region`: its TBAA tag, and for memory
/// that never changes while native code runs, `!invariant.load` (loads).
fn mem_metadata(region: Region, load: bool) -> String {
    let Some(k) = Region::ALL.iter().position(|&r| r == region) else { return String::new() };
    let tag = 6 + 2 * k;
    if load && region == Region::Const {
        format!(", !tbaa !{tag}, !invariant.load !3")
    } else {
        format!(", !tbaa !{tag}")
    }
}

/// Functions with more instructions than this are not vectorized.
const HUGE_FUNCTION: usize = 20_000;

fn ty(t: Type) -> &'static str {
    match t {
        Type::I8 => "i8",
        Type::I16 => "i16",
        Type::I32 => "i32",
        Type::I64 => "i64",
        Type::F32 => "float",
        Type::F64 => "double",
        Type::I64X2 => "<2 x i64>",
    }
}

/// The intrinsic name suffix of a scalar type.
fn suffix(t: Type) -> &'static str {
    match t {
        Type::I8 => "i8",
        Type::I16 => "i16",
        Type::I32 => "i32",
        Type::I64 => "i64",
        Type::F32 => "f32",
        Type::F64 => "f64",
        Type::I64X2 => "v2i64",
    }
}

fn param_type(p: &mir::AbiParam) -> String {
    let t = if p.ptr { "ptr" } else { ty(p.ty) };
    match p.ext {
        ArgExt::None => t.to_string(),
        ArgExt::Uext => format!("{t} zeroext"),
        ArgExt::Sext => format!("{t} signext"),
    }
}

fn param_types(sig: &Signature) -> String {
    sig.params.iter().map(param_type).collect::<Vec<_>>().join(", ")
}

/// The return type of a signature: `void`, a scalar, or a struct of the
/// returned values (returned in registers, as C returns a `JSValue`).
fn ret_type(sig: &Signature) -> String {
    match sig.returns.as_slice() {
        [] => "void".into(),
        [r] => {
            let t = if r.ptr { "ptr" } else { ty(r.ty) };
            match r.ext {
                ArgExt::None => t.into(),
                ArgExt::Uext => format!("zeroext {t}"),
                ArgExt::Sext => format!("signext {t}"),
            }
        }
        rs => struct_type(rs),
    }
}

fn struct_type(rs: &[mir::AbiParam]) -> String {
    format!("{{ {} }}", rs.iter().map(|r| ty(r.ty)).collect::<Vec<_>>().join(", "))
}

fn int_cc(cc: IntCC) -> &'static str {
    match cc {
        IntCC::Equal => "eq",
        IntCC::NotEqual => "ne",
        IntCC::SignedLessThan => "slt",
        IntCC::SignedGreaterThanOrEqual => "sge",
        IntCC::SignedGreaterThan => "sgt",
        IntCC::SignedLessThanOrEqual => "sle",
        IntCC::UnsignedLessThan => "ult",
        IntCC::UnsignedGreaterThanOrEqual => "uge",
        IntCC::UnsignedGreaterThan => "ugt",
        IntCC::UnsignedLessThanOrEqual => "ule",
    }
}

fn float_cc(cc: FloatCC) -> &'static str {
    match cc {
        FloatCC::Ordered => "ord",
        FloatCC::Unordered => "uno",
        FloatCC::Equal => "oeq",
        FloatCC::NotEqual => "une",
        FloatCC::OrderedNotEqual => "one",
        FloatCC::LessThan => "olt",
        FloatCC::LessThanOrEqual => "ole",
        FloatCC::GreaterThan => "ogt",
        FloatCC::GreaterThanOrEqual => "oge",
    }
}

/// How a block receives its parameters from one predecessor edge.
#[derive(Clone, Copy)]
enum Edge {
    /// The arguments of a `jump`, or of one side of a `brif`.
    Jump(mir::Inst),
    Then(mir::Inst),
    Else(mir::Inst),
    /// A `brif` with both sides on the block, with different arguments:
    /// `select`s made before the branch.
    Selected(mir::Inst),
}

fn edge_inst(e: Edge) -> mir::Inst {
    match e {
        Edge::Jump(i) | Edge::Then(i) | Edge::Else(i) | Edge::Selected(i) => i,
    }
}

struct FnEmitter<'a> {
    m: &'a mir::Module,
    f: &'a mir::Function,
    out: String,
    tmps: usize,
    intrinsics: &'a mut BTreeSet<String>,
    /// Literals of constants.
    consts: HashMap<Value, String>,
    /// `i1` twins of booleans.
    bools: HashMap<Value, String>,
    /// Values used as addresses (they get a `ptr` twin).
    ptr_like: Vec<bool>,
    /// `ptr` twins that are not `%vN.p`.
    ptrs: HashMap<Value, String>,
    reachable: Vec<bool>,
    /// Incoming edges of each block: the predecessor and how.
    preds: Vec<Vec<(Block, Edge)>>,
}

impl<'a> FnEmitter<'a> {
    fn new(m: &'a mir::Module, f: &'a mir::Function, intrinsics: &'a mut BTreeSet<String>) -> Self {
        let n = f.value_types.len();
        let mut e = FnEmitter {
            m,
            f,
            out: String::new(),
            tmps: 0,
            intrinsics,
            consts: HashMap::new(),
            bools: HashMap::new(),
            ptr_like: vec![false; n],
            ptrs: HashMap::new(),
            reachable: vec![false; f.blocks.len()],
            preds: vec![Vec::new(); f.blocks.len()],
        };
        e.analyze();
        e
    }

    fn analyze(&mut self) {
        let f = self.f;
        // Reachable blocks and their incoming edges.
        let mut stack = vec![f.entry];
        self.reachable[f.entry.index()] = true;
        while let Some(b) = stack.pop() {
            let last = *f.blocks[b.index()].insts.last().unwrap();
            let edges = match f.inst(last) {
                InstData::Jump { dest, .. } => vec![(*dest, Edge::Jump(last))],
                InstData::Brif { then, els, then_args, else_args, .. } if then == els => {
                    if then_args == else_args {
                        vec![(*then, Edge::Then(last))]
                    } else {
                        vec![(*then, Edge::Selected(last))]
                    }
                }
                InstData::Brif { then, els, .. } => vec![(*then, Edge::Then(last)), (*els, Edge::Else(last))],
                _ => vec![],
            };
            for (dest, edge) in edges {
                assert!(dest != f.entry, "a branch to the entry block");
                self.preds[dest.index()].push((b, edge));
                if !self.reachable[dest.index()] {
                    self.reachable[dest.index()] = true;
                    stack.push(dest);
                }
            }
        }
        // Constants and the natural `ptr` twins.
        for (i, inst) in f.insts.iter().enumerate() {
            let rs = &f.results[i];
            match *inst {
                InstData::Iconst { imm, .. } => {
                    self.consts.insert(rs[0], imm.to_string());
                }
                InstData::F64const(bits) => {
                    self.consts.insert(rs[0], format!("0x{bits:016X}"));
                }
                InstData::SymbolValue { data } => {
                    self.ptrs.insert(rs[0], format!("@{}", self.m.data[data.index()].name));
                }
                InstData::StackAddr { slot, off: 0 } => {
                    self.ptrs.insert(rs[0], format!("%slot{}", slot.index()));
                }
                _ => {}
            }
        }
        // Values used as addresses, and the values they derive from.
        let mut like = vec![false; f.value_types.len()];
        for inst in &f.insts {
            match inst {
                InstData::Load { addr, .. } | InstData::Store { addr, .. } => like[addr.index()] = true,
                InstData::Call { func, args } => {
                    for (p, a) in self.m.funcs[func.index()].sig.params.iter().zip(args) {
                        like[a.index()] |= p.ptr;
                    }
                }
                InstData::CallIndirect { sig, callee, args } => {
                    like[callee.index()] = true;
                    for (p, a) in self.m.sigs[sig.index()].params.iter().zip(args) {
                        like[a.index()] |= p.ptr;
                    }
                }
                InstData::Return { vals } => {
                    for (p, a) in f.sig.returns.iter().zip(vals) {
                        like[a.index()] |= p.ptr;
                    }
                }
                _ => {}
            }
        }
        for (p, &v) in f.sig.params.iter().zip(&f.blocks[f.entry.index()].params) {
            like[v.index()] |= p.ptr;
        }
        loop {
            let mut changed = false;
            let mut mark = |v: Value, like: &mut Vec<bool>| {
                if !like[v.index()] {
                    like[v.index()] = true;
                    changed = true;
                }
            };
            for (i, inst) in f.insts.iter().enumerate().rev() {
                let rs = &f.results[i];
                match *inst {
                    InstData::Binary { op: BinOp::Iadd, a, .. } if like[rs[0].index()] => mark(a, &mut like),
                    InstData::Select { a, b, .. } if like[rs[0].index()] => {
                        mark(a, &mut like);
                        mark(b, &mut like);
                    }
                    _ => {}
                }
                for (dest, args) in inst.successors() {
                    for (&p, &a) in f.blocks[dest.index()].params.iter().zip(args) {
                        if like[p.index()] {
                            mark(a, &mut like);
                        }
                    }
                }
            }
            if !changed {
                break;
            }
        }
        self.ptr_like = like;
    }

    fn tmp(&mut self) -> String {
        self.tmps += 1;
        format!("%t{}", self.tmps)
    }

    fn line(&mut self, s: impl AsRef<str>) {
        self.out.push_str("  ");
        self.out.push_str(s.as_ref());
        self.out.push('\n');
    }

    fn intrinsic(&mut self, decl: String) {
        self.intrinsics.insert(decl);
    }

    fn ty(&self, v: Value) -> &'static str {
        ty(self.f.value_type(v))
    }

    /// A value as an operand.
    fn val(&self, v: Value) -> String {
        match self.consts.get(&v) {
            Some(c) => c.clone(),
            None => format!("%v{}", v.index()),
        }
    }

    /// The `ptr` twin of a value used as an address.
    fn pval(&self, v: Value) -> String {
        if let Some(p) = self.ptrs.get(&v) {
            return p.clone();
        }
        match self.consts.get(&v).map(String::as_str) {
            Some("0") => "null".into(),
            Some(c) => format!("inttoptr (i64 {c} to ptr)"),
            None => format!("%v{}.p", v.index()),
        }
    }

    /// The `i1` twin of a boolean, if known.
    fn bool_of(&self, v: Value) -> Option<String> {
        if let Some(b) = self.bools.get(&v) {
            return Some(b.clone());
        }
        match (self.f.value_type(v), self.consts.get(&v).map(String::as_str)) {
            (Type::I8, Some("0")) => Some("false".into()),
            (Type::I8, Some("1")) => Some("true".into()),
            _ => None,
        }
    }

    /// A branch or select condition: nonzero.
    fn cond(&mut self, v: Value) -> String {
        if let Some(b) = self.bool_of(v) {
            return b;
        }
        let t = self.tmp();
        let line = format!("{t} = icmp ne {} {}, 0", self.ty(v), self.val(v));
        self.line(line);
        t
    }

    /// The `ptr` twin of `v`, unless it has a natural one: right after its
    /// definition.
    fn ensure_ptr(&mut self, v: Value) {
        if self.ptr_like[v.index()] && !self.ptrs.contains_key(&v) && !self.consts.contains_key(&v) {
            let line = format!("%v{n}.p = inttoptr i64 %v{n} to ptr", n = v.index());
            self.line(line);
        }
    }

    /// The address `addr + off`, as a `ptr`.
    fn address(&mut self, addr: Value, off: i32) -> String {
        let base = self.pval(addr);
        if off == 0 {
            return base;
        }
        let t = self.tmp();
        self.line(format!("{t} = getelementptr i8, ptr {base}, i64 {off}"));
        t
    }

    fn slot_address(&mut self, slot: mir::StackSlot, off: i32) -> String {
        if off == 0 {
            return format!("%slot{}", slot.index());
        }
        let t = self.tmp();
        self.line(format!("{t} = getelementptr inbounds i8, ptr %slot{}, i64 {off}", slot.index()));
        t
    }

    fn function(&mut self, name: &str, linkage: Linkage) -> String {
        let f = self.f;
        let entry = &f.blocks[f.entry.index()];
        let params: Vec<String> = f
            .sig
            .params
            .iter()
            .zip(&entry.params)
            .map(|(p, &v)| {
                if p.ptr {
                    format!("{} %v{}.p", param_type(p), v.index())
                } else {
                    format!("{} %v{}", param_type(p), v.index())
                }
            })
            .collect();
        let linkage = if linkage == Linkage::Local { "internal " } else { "dso_local " };
        let attrs = if f.no_vectorize || f.insts.len() > HUGE_FUNCTION { 2 } else { 1 };
        let mut head = format!("define {linkage}{} @{name}({}) #{attrs} {{\n", ret_type(&f.sig), params.join(", "));
        head.push_str("entry:\n");
        self.out = head;
        for (i, s) in f.slots.iter().enumerate() {
            self.line(format!("%slot{i} = alloca [{} x i8], align {}", s.size.max(1), 1u32 << s.align_shift));
        }
        for (i, &t) in f.vars.iter().enumerate() {
            let zero = if t.is_float() { "0.0" } else { "0" };
            self.line(format!("%var{i} = alloca {}", ty(t)));
            self.line(format!("store {} {zero}, ptr %var{i}", ty(t)));
        }
        for (p, &v) in f.sig.params.iter().zip(&entry.params) {
            if p.ptr {
                self.line(format!("%v{n} = ptrtoint ptr %v{n}.p to i64", n = v.index()));
            } else {
                self.ensure_ptr(v);
            }
        }
        self.line(format!("br label %b{}", f.entry.index()));
        for &b in &f.layout {
            if self.reachable[b.index()] {
                self.block(b);
            }
        }
        self.out.push_str("}\n\n");
        std::mem::take(&mut self.out)
    }

    /// The value an edge passes to parameter `k` of its block (`ptr`: its
    /// `ptr` twin).
    fn incoming(&self, edge: Edge, k: usize, ptr: bool) -> String {
        let args = match (edge, self.f.inst(edge_inst(edge))) {
            (Edge::Jump(_), InstData::Jump { args, .. }) => args,
            (Edge::Then(_), InstData::Brif { then_args, .. }) => then_args,
            (Edge::Else(_), InstData::Brif { else_args, .. }) => else_args,
            (Edge::Selected(i), _) => return format!("%sel{}_{k}{}", i.index(), if ptr { ".p" } else { "" }),
            _ => unreachable!("edge kind"),
        };
        if ptr { self.pval(args[k]) } else { self.val(args[k]) }
    }

    fn block(&mut self, b: Block) {
        let f = self.f;
        writeln!(self.out, "b{}:", b.index()).unwrap();
        if b != f.entry {
            let preds = self.preds[b.index()].clone();
            for (k, &p) in f.blocks[b.index()].params.iter().enumerate() {
                let t = self.ty(p);
                let ins: Vec<String> = preds
                    .iter()
                    .map(|&(pb, e)| format!("[ {}, %b{} ]", self.incoming(e, k, false), pb.index()))
                    .collect();
                self.line(format!("%v{} = phi {t} {}", p.index(), ins.join(", ")));
                if self.ptr_like[p.index()] {
                    let ins: Vec<String> = preds
                        .iter()
                        .map(|&(pb, e)| format!("[ {}, %b{} ]", self.incoming(e, k, true), pb.index()))
                        .collect();
                    self.line(format!("%v{}.p = phi ptr {}", p.index(), ins.join(", ")));
                }
            }
        }
        for &inst in &f.blocks[b.index()].insts {
            self.inst(inst);
        }
    }

    fn intrinsic1(&mut self, name: &str, t: Type, arg: &str) -> String {
        let (tn, s) = (ty(t), suffix(t));
        self.intrinsic(format!("declare {tn} @llvm.{name}.{s}({tn})"));
        format!("call {tn} @llvm.{name}.{s}({tn} {arg})")
    }

    fn intrinsic2(&mut self, name: &str, t: Type, a: &str, b: &str) -> String {
        let (tn, s) = (ty(t), suffix(t));
        self.intrinsic(format!("declare {tn} @llvm.{name}.{s}({tn}, {tn})"));
        format!("call {tn} @llvm.{name}.{s}({tn} {a}, {tn} {b})")
    }

    /// Branch weights for a `brif` with a cold side.
    fn weights(&self, then: Block, els: Block) -> &'static str {
        match (self.f.blocks[then.index()].cold, self.f.blocks[els.index()].cold) {
            (true, false) => ", !prof !1",
            (false, true) => ", !prof !2",
            _ => "",
        }
    }

    fn call_args(&self, sig: &Signature, args: &[Value]) -> String {
        sig.params
            .iter()
            .zip(args)
            .map(|(p, &a)| {
                if p.ptr {
                    format!("{} {}", param_type(p), self.pval(a))
                } else {
                    format!("{} {}", param_type(p), self.val(a))
                }
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    /// Bind the results of a call (`callee` and its arguments, as text).
    fn call(&mut self, sig: &Signature, callee: &str, args: &str, results: &[Value]) {
        let rt = ret_type(sig);
        match sig.returns.as_slice() {
            [] => self.line(format!("call void {callee}({args})")),
            [r] if r.ptr => {
                let n = results[0].index();
                self.line(format!("%v{n}.p = call {rt} {callee}({args})"));
                self.line(format!("%v{n} = ptrtoint ptr %v{n}.p to i64"));
            }
            [_] => {
                self.line(format!("%v{} = call {rt} {callee}({args})", results[0].index()));
                self.ensure_ptr(results[0]);
            }
            rs => {
                let t = self.tmp();
                self.line(format!("{t} = call {rt} {callee}({args})"));
                for (k, &v) in results.iter().enumerate() {
                    self.line(format!("%v{} = extractvalue {} {t}, {k}", v.index(), struct_type(rs)));
                    self.ensure_ptr(v);
                }
            }
        }
    }

    fn inst(&mut self, inst: mir::Inst) {
        let f = self.f;
        let results = f.inst_results(inst);
        let name = results.first().map(|r| format!("%v{}", r.index())).unwrap_or_default();
        match f.inst(inst) {
            InstData::Iconst { .. } | InstData::F64const(_) => {}
            &InstData::Unary { op, arg } => {
                let t = f.value_type(arg);
                let (tn, a) = (ty(t), self.val(arg));
                let rhs = match op {
                    UnOp::Ineg => format!("sub {tn} 0, {a}"),
                    UnOp::Bnot => format!("xor {tn} {a}, -1"),
                    UnOp::Iabs | UnOp::Clz => {
                        let n = if op == UnOp::Iabs { "abs" } else { "ctlz" };
                        let s = suffix(t);
                        self.intrinsic(format!("declare {tn} @llvm.{n}.{s}({tn}, i1)"));
                        format!("call {tn} @llvm.{n}.{s}({tn} {a}, i1 false)")
                    }
                    UnOp::Fneg => format!("fneg {tn} {a}"),
                    UnOp::Fabs => self.intrinsic1("fabs", t, &a),
                    UnOp::Sqrt => self.intrinsic1("sqrt", t, &a),
                    UnOp::Floor => self.intrinsic1("floor", t, &a),
                    UnOp::Ceil => self.intrinsic1("ceil", t, &a),
                    UnOp::Trunc => self.intrinsic1("trunc", t, &a),
                    UnOp::Nearest => self.intrinsic1("roundeven", t, &a),
                };
                self.line(format!("{name} = {rhs}"));
            }
            &InstData::Binary { op, a, b } => self.binary(results[0], op, a, b),
            &InstData::Conv { op, ty: to, arg } => {
                let from = f.value_type(arg);
                let a = self.val(arg);
                let (fname, tname) = (ty(from), ty(to));
                let rhs = match op {
                    ConvOp::Uextend => match self.bool_of(arg) {
                        Some(bv) => format!("zext i1 {bv} to {tname}"),
                        None => format!("zext {fname} {a} to {tname}"),
                    },
                    ConvOp::Sextend => format!("sext {fname} {a} to {tname}"),
                    ConvOp::Ireduce => format!("trunc {fname} {a} to {tname}"),
                    ConvOp::FromSint => format!("sitofp {fname} {a} to {tname}"),
                    ConvOp::FromUint => format!("uitofp {fname} {a} to {tname}"),
                    ConvOp::ToSintSat | ConvOp::ToUintSat => {
                        let n = if op == ConvOp::ToSintSat { "fptosi" } else { "fptoui" };
                        let (ts, fs) = (suffix(to), suffix(from));
                        self.intrinsic(format!("declare {tname} @llvm.{n}.sat.{ts}.{fs}({fname})"));
                        format!("call {tname} @llvm.{n}.sat.{ts}.{fs}({fname} {a})")
                    }
                    ConvOp::Fpromote => format!("fpext {fname} {a} to {tname}"),
                    ConvOp::Fdemote => format!("fptrunc {fname} {a} to {tname}"),
                    ConvOp::Bitcast => format!("bitcast {fname} {a} to {tname}"),
                };
                self.line(format!("{name} = {rhs}"));
                self.ensure_ptr(results[0]);
            }
            &InstData::Icmp { cc, a, b } => {
                let line = format!("{name}.b = icmp {} {} {}, {}", int_cc(cc), self.ty(a), self.val(a), self.val(b));
                self.line(line);
                self.line(format!("{name} = zext i1 {name}.b to i8"));
                self.bools.insert(results[0], format!("{name}.b"));
            }
            &InstData::Fcmp { cc, a, b } => {
                let line = format!("{name}.b = fcmp {} {} {}, {}", float_cc(cc), self.ty(a), self.val(a), self.val(b));
                self.line(line);
                self.line(format!("{name} = zext i1 {name}.b to i8"));
                self.bools.insert(results[0], format!("{name}.b"));
            }
            &InstData::Select { cond, a, b } => {
                let c = self.cond(cond);
                let t = self.ty(a);
                match (t, self.bool_of(a), self.bool_of(b)) {
                    ("i8", Some(x), Some(y)) => {
                        self.line(format!("{name}.b = select i1 {c}, i1 {x}, i1 {y}"));
                        self.line(format!("{name} = zext i1 {name}.b to i8"));
                        self.bools.insert(results[0], format!("{name}.b"));
                    }
                    _ => {
                        let line = format!("{name} = select i1 {c}, {t} {}, {t} {}", self.val(a), self.val(b));
                        self.line(line);
                    }
                }
                if self.ptr_like[results[0].index()] {
                    let line = format!("{name}.p = select i1 {c}, ptr {}, ptr {}", self.pval(a), self.pval(b));
                    self.line(line);
                }
            }
            &InstData::Overflow { sub, a, b } => {
                let t = f.value_type(a);
                let (tn, s) = (ty(t), suffix(t));
                let op = if sub { "ssub" } else { "sadd" };
                self.intrinsic(format!("declare {{ {tn}, i1 }} @llvm.{op}.with.overflow.{s}({tn}, {tn})"));
                let tmp = self.tmp();
                let line = format!(
                    "{tmp} = call {{ {tn}, i1 }} @llvm.{op}.with.overflow.{s}({tn} {}, {tn} {})",
                    self.val(a),
                    self.val(b)
                );
                self.line(line);
                self.line(format!("{name} = extractvalue {{ {tn}, i1 }} {tmp}, 0"));
                let flag = format!("%v{}", results[1].index());
                self.line(format!("{flag}.b = extractvalue {{ {tn}, i1 }} {tmp}, 1"));
                self.line(format!("{flag} = zext i1 {flag}.b to i8"));
                self.bools.insert(results[1], format!("{flag}.b"));
            }
            &InstData::Load { ty: t, mem, signed, flags, addr, off } => {
                let p = self.address(addr, off);
                let align = mem.bytes();
                let md = mem_metadata(flags.region, true);
                if mem == t && t == Type::I64 && self.ptr_like[results[0].index()] {
                    // A pointer, loaded as one.
                    self.line(format!("{name}.p = load ptr, ptr {p}, align {align}{md}"));
                    self.line(format!("{name} = ptrtoint ptr {name}.p to i64"));
                } else if mem == t {
                    self.line(format!("{name} = load {}, ptr {p}, align {align}{md}", ty(t)));
                    self.ensure_ptr(results[0]);
                } else {
                    let tmp = self.tmp();
                    self.line(format!("{tmp} = load {}, ptr {p}, align {align}{md}", ty(mem)));
                    let ext = if signed { "sext" } else { "zext" };
                    self.line(format!("{name} = {ext} {} {tmp} to {}", ty(mem), ty(t)));
                    self.ensure_ptr(results[0]);
                }
            }
            &InstData::Store { mem, flags, val, addr, off } => {
                let p = self.address(addr, off);
                let vt = f.value_type(val);
                let v = if vt == mem {
                    self.val(val)
                } else {
                    let tmp = self.tmp();
                    let line = format!("{tmp} = trunc {} {} to {}", ty(vt), self.val(val), ty(mem));
                    self.line(line);
                    tmp
                };
                let md = mem_metadata(flags.region, false);
                self.line(format!("store {} {v}, ptr {p}, align {}{md}", ty(mem), mem.bytes()));
            }
            &InstData::StackAddr { slot, off } => {
                if off == 0 {
                    self.line(format!("{name} = ptrtoint ptr %slot{} to i64", slot.index()));
                } else {
                    self.line(format!("{name}.p = getelementptr inbounds i8, ptr %slot{}, i64 {off}", slot.index()));
                    self.line(format!("{name} = ptrtoint ptr {name}.p to i64"));
                }
            }
            &InstData::StackLoad { ty: t, slot, off } => {
                let p = self.slot_address(slot, off);
                self.line(format!("{name} = load {}, ptr {p}, align {}", ty(t), t.bytes()));
                self.ensure_ptr(results[0]);
            }
            &InstData::StackStore { val, slot, off } => {
                let p = self.slot_address(slot, off);
                let t = f.value_type(val);
                let line = format!("store {} {}, ptr {p}, align {}", ty(t), self.val(val), t.bytes());
                self.line(line);
            }
            &InstData::StackStorePair { lo, hi, slot, off } => {
                let p = self.slot_address(slot, off);
                let align = if off % 16 == 0 && f.slots[slot.index()].align_shift >= 4 { 16 } else { 8 };
                let (t1, t2) = (self.tmp(), self.tmp());
                let line = format!("{t1} = insertelement <2 x i64> poison, i64 {}, i32 0", self.val(lo));
                self.line(line);
                let line = format!("{t2} = insertelement <2 x i64> {t1}, i64 {}, i32 1", self.val(hi));
                self.line(line);
                self.line(format!("store <2 x i64> {t2}, ptr {p}, align {align}"));
            }
            &InstData::SymbolValue { data } => {
                self.line(format!("{name} = ptrtoint ptr @{} to i64", self.m.data[data.index()].name));
            }
            &InstData::FuncAddr { func } => {
                self.line(format!("{name} = ptrtoint ptr @{} to i64", self.m.funcs[func.index()].name));
                self.ensure_ptr(results[0]);
            }
            InstData::StackPointer => {
                self.intrinsic("declare i64 @llvm.read_register.i64(metadata)".into());
                self.line(format!("{name} = call i64 @llvm.read_register.i64(metadata !0)"));
                self.ensure_ptr(results[0]);
            }
            InstData::Call { func, args } => {
                let decl = &self.m.funcs[func.index()];
                let args = self.call_args(&decl.sig, args);
                self.call(&decl.sig, &format!("@{}", decl.name), &args, results);
            }
            InstData::CallIndirect { sig, callee, args } => {
                let sig = &self.m.sigs[sig.index()];
                let args = self.call_args(sig, args);
                let callee = self.pval(*callee);
                self.call(sig, &callee, &args, results);
            }
            &InstData::UseVar { var } => {
                let t = ty(f.vars[var.index()]);
                self.line(format!("{name} = load {t}, ptr %var{}", var.index()));
                self.ensure_ptr(results[0]);
            }
            &InstData::DefVar { var, val } => {
                let t = ty(f.vars[var.index()]);
                let line = format!("store {t} {}, ptr %var{}", self.val(val), var.index());
                self.line(line);
            }
            InstData::Jump { dest, .. } => self.line(format!("br label %b{}", dest.index())),
            InstData::Brif { cond, then, then_args, els, else_args } => {
                if then == els {
                    if then_args != else_args {
                        // One edge: the arguments are selected first.
                        let c = self.cond(*cond);
                        let params = f.blocks[then.index()].params.clone();
                        for (k, &p) in params.iter().enumerate() {
                            let t = self.ty(p);
                            let line = format!(
                                "%sel{}_{k} = select i1 {c}, {t} {}, {t} {}",
                                inst.index(),
                                self.val(then_args[k]),
                                self.val(else_args[k])
                            );
                            self.line(line);
                            if self.ptr_like[p.index()] {
                                let line = format!(
                                    "%sel{}_{k}.p = select i1 {c}, ptr {}, ptr {}",
                                    inst.index(),
                                    self.pval(then_args[k]),
                                    self.pval(else_args[k])
                                );
                                self.line(line);
                            }
                        }
                    }
                    self.line(format!("br label %b{}", then.index()));
                } else {
                    let c = self.cond(*cond);
                    let w = self.weights(*then, *els);
                    self.line(format!("br i1 {c}, label %b{}, label %b{}{w}", then.index(), els.index()));
                }
            }
            InstData::Return { vals } => match f.sig.returns.as_slice() {
                [] => self.line("ret void"),
                [r] => {
                    let v = if r.ptr { self.pval(vals[0]) } else { self.val(vals[0]) };
                    self.line(format!("ret {} {v}", if r.ptr { "ptr" } else { ty(r.ty) }));
                }
                rs => {
                    let st = struct_type(rs);
                    let mut acc = "poison".to_string();
                    for (k, &v) in vals.iter().enumerate() {
                        let t = self.tmp();
                        let line = format!("{t} = insertvalue {st} {acc}, {} {}, {k}", self.ty(v), self.val(v));
                        self.line(line);
                        acc = t;
                    }
                    self.line(format!("ret {st} {acc}"));
                }
            },
            InstData::Trap => {
                self.intrinsic("declare void @llvm.trap() cold noreturn nounwind".into());
                self.line("call void @llvm.trap()");
                self.line("unreachable");
            }
        }
    }

    fn binary(&mut self, r: Value, op: BinOp, a: Value, b: Value) {
        let f = self.f;
        let name = format!("%v{}", r.index());
        let t = f.value_type(a);
        let tn = ty(t);
        let (x, y) = (self.val(a), self.val(b));
        // Booleans stay booleans through `&`, `|`, `^`.
        if let (BinOp::Band | BinOp::Bor | BinOp::Bxor, Type::I8, Some(xb), Some(yb)) =
            (op, t, self.bool_of(a), self.bool_of(b))
        {
            let o = match op {
                BinOp::Band => "and",
                BinOp::Bor => "or",
                _ => "xor",
            };
            self.line(format!("{name}.b = {o} i1 {xb}, {yb}"));
            self.line(format!("{name} = zext i1 {name}.b to i8"));
            self.bools.insert(r, format!("{name}.b"));
            return;
        }
        let rhs = match op {
            BinOp::Iadd => format!("add {tn} {x}, {y}"),
            BinOp::Isub => format!("sub {tn} {x}, {y}"),
            BinOp::Imul => format!("mul {tn} {x}, {y}"),
            BinOp::Band => format!("and {tn} {x}, {y}"),
            BinOp::Bor => format!("or {tn} {x}, {y}"),
            BinOp::Bxor => format!("xor {tn} {x}, {y}"),
            BinOp::BandNot => {
                let n = self.tmp();
                self.line(format!("{n} = xor {tn} {y}, -1"));
                format!("and {tn} {x}, {n}")
            }
            BinOp::Ishl | BinOp::Ushr | BinOp::Sshr => {
                // The amount modulo the width.
                let bt = f.value_type(b);
                let m = self.tmp();
                self.line(format!("{m} = and {} {y}, {}", ty(bt), t.bits() - 1));
                let amt = if bt == t {
                    m
                } else {
                    let c = self.tmp();
                    let conv = if bt.bits() < t.bits() { "zext" } else { "trunc" };
                    self.line(format!("{c} = {conv} {} {m} to {tn}", ty(bt)));
                    c
                };
                let o = match op {
                    BinOp::Ishl => "shl",
                    BinOp::Ushr => "lshr",
                    _ => "ashr",
                };
                format!("{o} {tn} {x}, {amt}")
            }
            BinOp::Srem => {
                // `MIN % -1` is 0, as `MIN % 1`.
                let (m, d) = (self.tmp(), self.tmp());
                self.line(format!("{m} = icmp eq {tn} {y}, -1"));
                self.line(format!("{d} = select i1 {m}, {tn} 1, {tn} {y}"));
                format!("srem {tn} {x}, {d}")
            }
            BinOp::Fadd => format!("fadd {tn} {x}, {y}"),
            BinOp::Fsub => format!("fsub {tn} {x}, {y}"),
            BinOp::Fmul => format!("fmul {tn} {x}, {y}"),
            BinOp::Fdiv => format!("fdiv {tn} {x}, {y}"),
            BinOp::Fmin => self.intrinsic2("minimum", t, &x, &y),
            BinOp::Fmax => self.intrinsic2("maximum", t, &x, &y),
            BinOp::Fcopysign => self.intrinsic2("copysign", t, &x, &y),
        };
        self.line(format!("{name} = {rhs}"));
        if self.ptr_like[r.index()] {
            if op == BinOp::Iadd {
                let line = format!("{name}.p = getelementptr i8, ptr {}, {tn} {y}", self.pval(a));
                self.line(line);
            } else {
                self.ensure_ptr(r);
            }
        }
    }
}
