//! Generates the C glue between QuickJS and the native functions: the
//! `luminous:native` C module exporting `__lum_bind(i, fallback)`, which
//! creates the JS function object for native function `i`.
//!
//! The JS entry itself (`lum_fast_<i>`) is native code: the engine's
//! `JSCFunctionFast` hook calls it straight from the interpreter's call
//! opcodes. When it declines (ill-typed arguments), the engine calls the
//! regular C function, a shared trampoline into the interpreted fallback.

use std::fmt::Write;

use luminous_codegen::{NATIVE_STACK_BUDGET, jsvalue, layout};
use luminous_front::ClassDecl;
use luminous_front::erase::{
    BIND_FN, CELLS_OBJ, CLASS_FN, FALLBACK_PREFIX, INIT_FN, METHOD_FN, NATIVE_MODULE, SARR_FN, STRUCT_FN,
};
use luminous_front::ir;

/// C init function name passed to `qjsc -M luminous:native,<CNAME>`.
pub const MODULE_CNAME: &str = "luminous";

/// A C string literal; octal escapes for anything outside printable ASCII.
fn c_str(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' | b'\\' => write!(out, "\\{}", b as char).unwrap(),
            0x20..=0x7e => out.push(b as char),
            _ => write!(out, "\\{b:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}

/// `sources`: by native function, what `toString` gives for its closures
/// (see `ir::Func::source`).
pub fn generate(
    m: &ir::Module,
    mutable: &[(usize, bool)],
    classes: &[ClassDecl],
    int_wrapping: bool,
    sources: &[Option<String>],
) -> String {
    let mut c = String::new();
    write!(
        c,
        r#"/* Generated by luminous. */
#include <stddef.h>
#include <string.h>
#include "luminous_rt.h"

/* The native entries read and write JSValues directly: 8 bytes, NaN-boxed
   with compressed references. */
#if !defined(JS_COMPRESSED_POINTERS)
#error "luminous needs the engine built with JS_COMPRESSED_POINTERS"
#endif
_Static_assert(sizeof(JSValue) == {size}, "luminous needs 8-byte JSValues");
_Static_assert(JS_TAG_BASE == {base}u, "unexpected value encoding");
_Static_assert(JS_TAG_INT == {int} && JS_TAG_BOOL == {bool} && JS_TAG_UNDEFINED == {undef} &&
               JS_TAG_UNINITIALIZED == {uninit} && JS_TAG_EXCEPTION == {exc} &&
               JS_TAG_FLOAT64 == {f64} && JS_TAG_STRING == {string} && JS_TAG_NULL == {null},
               "unexpected JSValue tags");
_Static_assert(JS_BINOP_ADD == 0 && JS_BINOP_XOR == 11 && JS_BINOP_LT == 12 && JS_BINOP_INSTANCEOF == 21 &&
               JS_UNOP_NEG == 0 && JS_UNOP_TYPEOF == 6, "unexpected operator numbering");
_Static_assert(LUM_NATIVE_STACK == {budget}u, "stack budget mismatch");

"#,
        size = jsvalue::SIZE,
        base = jsvalue::TAG_BASE,
        int = jsvalue::TAG_INT,
        bool = jsvalue::TAG_BOOL,
        undef = jsvalue::TAG_UNDEFINED,
        uninit = jsvalue::TAG_UNINITIALIZED,
        exc = jsvalue::TAG_EXCEPTION,
        f64 = jsvalue::TAG_FLOAT64,
        string = jsvalue::TAG_STRING,
        null = jsvalue::TAG_NULL,
        budget = NATIVE_STACK_BUDGET,
    )
    .unwrap();
    for (name, v) in layout::ALL {
        writeln!(c, "_Static_assert(JS_LAYOUT_{name} == {v}, \"engine layout mismatch\");").unwrap();
    }
    c.push('\n');

    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        writeln!(c, "extern JSCFunctionFast lum_fast_{i}; /* {} */", f.name.replace("*/", "* /")).unwrap();
    }

    let n = m.funcs.len();
    let nclasses = m.homes / 2;
    let nall = n + m.closures.len();
    // Trailing sentinels keep arrays non-empty.
    // kind: 0 plain, 1 async, 2 generator, 3 async generator, 4 an ordinary
    // function (a constructor: see lum_function_kind), 5 a class
    // constructor.
    c.push_str(
        "\nstatic const struct { JSCFunctionFast *fast; const char *name; int length, kind; } lum_table[] = {\n",
    );
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        let kind = match (f.is_generator, f.is_async) {
            (true, true) => 3,
            (true, false) => 2,
            (false, true) => 1,
            (false, false) if f.class_ctor => 5,
            (false, false) => 4 * f.constructor as u8,
        };
        writeln!(c, "    {{ lum_fast_{i}, {}, {}, {kind} }},", c_str(&f.name), f.js_length).unwrap();
    }
    c.push_str("    { NULL, NULL, 0, 0 },\n};\n\n");
    writeln!(c, "LumFnCache lum_fn_caches[{}];\nconst int32_t lum_nfn_caches = {nall};\n", nall + 1).unwrap();
    c.push_str("/* What `toString` gives for native closures: their source, without types. */\n");
    c.push_str("static const char *const lum_sources[] = {\n");
    for i in 0..nall {
        match sources.get(i).and_then(|s| s.as_deref()) {
            Some(s) => writeln!(c, "    {},", c_str(s)).unwrap(),
            None => c.push_str("    NULL,\n"),
        }
    }
    c.push_str("    NULL,\n};\n\n");
    layouts(&mut c, m, int_wrapping);

    // Step functions of async functions and generators.
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        if f.suspends() {
            writeln!(c, "extern LumStep lum_fn_{i};").unwrap();
        }
    }
    c.push_str("LumStep *const lum_steps[] = {\n");
    for (i, f) in m.funcs.iter().chain(&m.closures).enumerate() {
        if f.suspends() {
            writeln!(c, "    lum_fn_{i},").unwrap();
        } else {
            c.push_str("    NULL,\n");
        }
    }
    c.push_str("    NULL,\n};\n\n");

    // Module state tables.
    let list = |items: Vec<String>| -> String {
        let mut s: String = items.into_iter().map(|i| format!("    {i},\n")).collect();
        s.push_str("    0\n");
        s
    };
    let (ncells, nstrings, natoms) = (m.cells.len(), m.strings.len(), m.atoms.len());
    writeln!(c, "JSValue lum_cells[{}];", ncells + 1).unwrap();
    writeln!(c, "JSValue lum_strings[{}];", nstrings + 1).unwrap();
    writeln!(c, "JSAtom lum_atoms[{}];", natoms + 1).unwrap();
    writeln!(
        c,
        "const int lum_ncells = {ncells}, lum_nstrings = {nstrings}, lum_natoms = {natoms}, lum_nmutable = {};",
        mutable.len()
    )
    .unwrap();
    write!(c, "const char *const lum_cell_names[] = {{\n{}}};\n", list(m.cells.iter().map(|s| c_str(s)).collect()))
        .unwrap();
    write!(c, "const char *const lum_atom_names[] = {{\n{}}};\n", list(m.atoms.iter().map(|s| c_str(s)).collect()))
        .unwrap();
    write!(
        c,
        "const char *const lum_string_data[] = {{\n{}}};\n",
        list(m.strings.iter().map(|s| c_str(s)).collect())
    )
    .unwrap();
    write!(
        c,
        "const size_t lum_string_lens[] = {{\n{}}};\n",
        list(m.strings.iter().map(|s| s.len().to_string()).collect())
    )
    .unwrap();
    write!(c, "const int lum_mutable_cells[] = {{\n{}}};\n", list(mutable.iter().map(|k| k.0.to_string()).collect()))
        .unwrap();
    write!(
        c,
        "const unsigned char lum_mutable_const[] = {{\n{}}};\n\n",
        list(mutable.iter().map(|k| (k.1 as u8).to_string()).collect())
    )
    .unwrap();

    // Classes: private name values and home objects, and what each class
    // hands over.
    writeln!(c, "JSValue lum_privates[{}];", m.privates + 1).unwrap();
    writeln!(c, "JSValue lum_homes[{}];", m.homes + 1).unwrap();
    writeln!(c, "const int lum_nprivates = {}, lum_nhomes = {};", m.privates, m.homes).unwrap();
    c.push_str("struct lum_class_var { const char *name; int slot; };\n");
    for cl in classes {
        writeln!(c, "static const struct lum_class_var lum_class_vars_{}[] = {{", cl.index).unwrap();
        for (name, slot) in &cl.vars {
            writeln!(c, "    {{ {}, {slot} }},", c_str(name)).unwrap();
        }
        c.push_str("    { NULL, 0 },\n};\n");
    }
    writeln!(c, "static const struct lum_class_var *const lum_class_vars[{}] = {{", m.homes / 2 + 1).unwrap();
    for cl in classes {
        writeln!(c, "    [{0}] = lum_class_vars_{0},", cl.index).unwrap();
    }
    c.push_str("};\n\n");

    write!(
        c,
        r#"/* Slow path, taken when a fast entry declines: the interpreted fallback. */
static JSValue lum_fallback(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                              int magic, JSValueConst *data)
{{
    return JS_Call(ctx, data[0], this_val, argc, argv);
}}

/* {BIND_FN}(i, fallback): the JS function object of native function i. */
static JSValue lum_bind(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t i;
    if (argc < 2 || JS_VALUE_GET_TAG(argv[0]) != JS_TAG_INT || !JS_IsFunction(ctx, argv[1]))
        return JS_ThrowTypeError(ctx, "{BIND_FN}: expected (index, fallback)");
    i = JS_VALUE_GET_INT(argv[0]);
    if (i < 0 || i >= {n})
        return JS_ThrowRangeError(ctx, "{BIND_FN}: bad index");
    return lum_function_kind(ctx, JS_NewCFunctionDataFast(ctx, lum_table[i].fast, lum_fallback,
                                                            lum_table[i].name, lum_table[i].length, 0,
                                                            1, &argv[1]),
                               argv[1], lum_table[i].kind);
}}

/* Closures never decline (all their parameters are JS values), but if the
 * engine calls their regular function anyway, go to the native entry. */
static JSValue lum_closure_slow(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                                  int magic, JSValueConst *data)
{{
    return lum_table[magic].fast(ctx, this_val, argc, argv, data);
}}

/* Function.prototype.toString of a native function: its interpreted
 * fallback's, or a closure's source. */
static JSValue lum_class_ctor_call(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                                   int magic, JSValueConst *data);

static JSValue lum_function_source(JSContext *ctx, JSCFunctionData *func, int magic, int data_len,
                                   JSValueConst *data)
{{
    if (func == lum_fallback && data_len > 0) {{
        /* (A declaration's fallback is named `{FALLBACK_PREFIX}<name>`.) */
        JSValue src = JS_FunctionToString(ctx, data[0]), r;
        size_t len;
        const char *s = JS_IsString(src) ? JS_ToCStringLen(ctx, &len, src) : NULL;
        const char *at = s ? strstr(s, "{FALLBACK_PREFIX}") : NULL;
        if (!at || at - s > 32 || memchr(s, '(', at - s)) {{
            JS_FreeCString(ctx, s);
            return src;
        }}
        {{
            size_t n = sizeof("{FALLBACK_PREFIX}") - 1;
            char *buf = js_malloc(ctx, len - n + 1);
            if (!buf) {{
                JS_FreeCString(ctx, s);
                return src;
            }}
            memcpy(buf, s, at - s);
            memcpy(buf + (at - s), at + n, len - (at - s) - n);
            r = JS_NewStringLen(ctx, buf, len - n);
            js_free(ctx, buf);
        }}
        JS_FreeCString(ctx, s);
        JS_FreeValue(ctx, src);
        return r;
    }}
    if ((func == lum_closure_slow || func == lum_class_ctor_call) && magic >= 0 && magic < {nall} &&
        lum_sources[magic])
        return JS_NewString(ctx, lum_sources[magic]);
    return JS_UNDEFINED;
}}

/* A closure of native function `fn` over `data` (borrowed). */
/* A class constructor's `new` (closure `magic`): its JS entry, with
   this_val new.target. */
static JSValue lum_class_ctor_call(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                                   int magic, JSValueConst *data)
{{
    return lum_table[magic].fast(ctx, this_val, argc, argv, data);
}}

JSValue lum_make_closure(JSContext *ctx, int fn, int n, JSValue *data)
{{
    int kind = lum_table[fn].kind;
    JSValue f = lum_new_closure(ctx, &lum_fn_caches[fn], lum_table[fn].fast, lum_closure_slow,
                                lum_table[fn].name, lum_table[fn].length, fn, n, data, kind);
    if (kind == 5) {{
        /* A class constructor (lum_class_setup gives it its prototype). */
        if (!JS_IsException(f))
            JS_SetCFunctionDataClassConstructor(ctx, f, lum_class_ctor_call);
        return f;
    }}
    return kind <= 1 ? f : lum_function_kind(ctx, f, JS_UNDEFINED, kind);
}}

/* {METHOD_FN}(i, Class, is_static, key, accessor): replace a class method
 * (accessor 0), getter (1) or setter (2) with native function i; the
 * interpreted one becomes its fallback. A method keeps the attributes of a
 * class method (writable, configurable, not enumerable); an accessor only
 * has its getter or setter replaced. */
static JSValue lum_method(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t i, is_static, accessor = 0;
    JSValue holder, fallback, stub;
    JSPropertyDescriptor desc;
    JSAtom key;
    int r;
    if (argc < 4 || JS_ToInt32(ctx, &i, argv[0]) || JS_ToInt32(ctx, &is_static, argv[2]) ||
        (argc > 4 && JS_ToInt32(ctx, &accessor, argv[4])) || i < 0 || i >= {nall})
        return JS_ThrowTypeError(ctx, "{METHOD_FN}: bad arguments");
    holder = is_static ? JS_DupValue(ctx, argv[1]) : JS_GetPropertyStr(ctx, argv[1], "prototype");
    if (JS_IsException(holder))
        return holder;
    key = JS_ValueToAtom(ctx, argv[3]);
    if (key == JS_ATOM_NULL) {{
        JS_FreeValue(ctx, holder);
        return JS_EXCEPTION;
    }}
    if (accessor) {{
        r = JS_GetOwnProperty(ctx, &desc, holder, key);
        fallback = JS_UNDEFINED;
        if (r > 0) {{
            fallback = JS_DupValue(ctx, accessor == 1 ? desc.getter : desc.setter);
            JS_FreeValue(ctx, desc.value);
            JS_FreeValue(ctx, desc.getter);
            JS_FreeValue(ctx, desc.setter);
        }} else if (r < 0) {{
            fallback = JS_EXCEPTION;
        }}
    }} else {{
        fallback = JS_GetProperty(ctx, holder, key);
    }}
    if (JS_IsException(fallback) || !JS_IsFunction(ctx, fallback)) {{
        JS_FreeValue(ctx, fallback);
        JS_FreeValue(ctx, holder);
        JS_FreeAtom(ctx, key);
        return JS_ThrowTypeError(ctx, "{METHOD_FN}: not a method");
    }}
    stub = lum_function_kind(ctx, JS_NewCFunctionDataFast(ctx, lum_table[i].fast, lum_fallback,
                                                            lum_table[i].name, lum_table[i].length, 0,
                                                            1, &fallback),
                               fallback, lum_table[i].kind);
    JS_FreeValue(ctx, fallback);
    if (JS_IsException(stub)) {{
        r = -1;
    }} else if (accessor) {{
        r = JS_DefineProperty(ctx, holder, key, JS_UNDEFINED, accessor == 1 ? stub : JS_UNDEFINED,
                              accessor == 2 ? stub : JS_UNDEFINED,
                              (accessor == 1 ? JS_PROP_HAS_GET : JS_PROP_HAS_SET) | JS_PROP_THROW);
        JS_FreeValue(ctx, stub);
    }} else {{
        r = JS_DefinePropertyValue(ctx, holder, key, stub, JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE | JS_PROP_THROW);
    }}
    JS_FreeValue(ctx, holder);
    JS_FreeAtom(ctx, key);
    return r < 0 ? JS_EXCEPTION : JS_UNDEFINED;
}}

/* {CLASS_FN}(k, Class, fn) in a static block of class k: its home objects,
 * and the values of the private names that `fn` references. */
static JSValue lum_class(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{{
    int32_t k;
    const struct lum_class_var *v;
    JSValue proto;
    if (argc < 3 || JS_ToInt32(ctx, &k, argv[0]) || k < 0 || k >= {nclasses} || !lum_class_vars[k])
        return JS_ThrowTypeError(ctx, "{CLASS_FN}: bad arguments");
    proto = JS_GetPropertyStr(ctx, argv[1], "prototype");
    if (JS_IsException(proto))
        return proto;
    JS_FreeValue(ctx, lum_homes[2 * k]);
    JS_FreeValue(ctx, lum_homes[2 * k + 1]);
    lum_homes[2 * k] = proto;
    lum_homes[2 * k + 1] = JS_DupValue(ctx, argv[1]);
    for (v = lum_class_vars[k]; v->name; v++) {{
        JSAtom name = JS_NewAtom(ctx, v->name);
        JSValue val;
        if (name == JS_ATOM_NULL)
            return JS_EXCEPTION;
        if (JS_GetClosureVariable(ctx, argv[2], name, &val)) {{
            JS_FreeValue(ctx, lum_privates[v->slot]);
            lum_privates[v->slot] = val;
        }}
        JS_FreeAtom(ctx, name);
    }}
    return JS_UNDEFINED;
}}

static JSValue lum_exports[4];

/* (The collector's roots until the module holds them.) */
static void lum_mark_exports(JSRuntime *rt, void *opaque, JS_MarkFunc *mark_func)
{{
    for (int i = 0; i < 3; i++)
        JS_MarkValue(rt, lum_exports[i], mark_func);
}}

static int lum_module_init(JSContext *ctx, JSModuleDef *m)
{{
    JSValue state = lum_exports[0], init = lum_exports[1], cells = lum_exports[2];
    lum_exports[0] = lum_exports[1] = lum_exports[2] = JS_UNDEFINED;
    if (JS_SetModuleExport(ctx, m, "{BIND_FN}",
                           JS_NewCFunction(ctx, lum_bind, "{BIND_FN}", 2)) < 0)
        return -1;
    /* The module owns the state object: its finalizer releases the cells. */
    if (JS_SetModuleExport(ctx, m, "__lum_state", state) < 0 ||
        JS_SetModuleExport(ctx, m, "{INIT_FN}", init) < 0 ||
        JS_SetModuleExport(ctx, m, "{CELLS_OBJ}", cells) < 0 ||
        JS_SetModuleExport(ctx, m, "{METHOD_FN}",
                           JS_NewCFunction(ctx, lum_method, "{METHOD_FN}", 5)) < 0)
        return -1;
    if (JS_SetModuleExport(ctx, m, "{CLASS_FN}", JS_NewCFunction(ctx, lum_class, "{CLASS_FN}", 3)) < 0)
        return -1;
    if (JS_SetModuleExport(ctx, m, "{STRUCT_FN}", JS_NewCFunction(ctx, lum_struct_from, "{STRUCT_FN}", 2)) < 0)
        return -1;
    if (JS_SetModuleExport(ctx, m, "{SARR_FN}", JS_NewCFunction(ctx, lum_sarr_js, "{SARR_FN}", 2)) < 0)
        return -1;
    return 0;
}}

/* Registered as "{NATIVE_MODULE}"; called while the context is created,
 * before any JS runs. */
JSModuleDef *js_init_module_{MODULE_CNAME}(JSContext *ctx, const char *name)
{{
    JSModuleDef *m;
    if (JS_AddGCMarkHook(JS_GetRuntime(ctx), lum_mark_exports, NULL) < 0)
        return NULL;
    JS_SetFunctionSourceHook(JS_GetRuntime(ctx), lum_function_source);
    if (lum_runtime_init(ctx, &lum_exports[0], &lum_exports[1], &lum_exports[2]) < 0)
        return NULL;
    m = JS_NewCModule(ctx, name, lum_module_init);
    if (!m)
        return NULL;
    JS_AddModuleExport(ctx, m, "{BIND_FN}");
    JS_AddModuleExport(ctx, m, "__lum_state");
    JS_AddModuleExport(ctx, m, "{INIT_FN}");
    JS_AddModuleExport(ctx, m, "{CELLS_OBJ}");
    JS_AddModuleExport(ctx, m, "{METHOD_FN}");
    JS_AddModuleExport(ctx, m, "{CLASS_FN}");
    JS_AddModuleExport(ctx, m, "{STRUCT_FN}");
    JS_AddModuleExport(ctx, m, "{SARR_FN}");
    return m;
}}
"#
    )
    .unwrap();
    c
}

/// The function writing the JSON of the objects of layout `k` (as the
/// general way, `lum_struct_json_from`, writes them): its name, or `None`
/// when a key needs escapes. Straight-line code: keys as constants, values
/// at their offsets, the room for each run of fields up to a JS value
/// (a string or an object) reserved at once; where room cannot be had (the
/// output has 16-bit characters), the general way continues.
fn json_writer(c: &mut String, k: usize, l: &ir::Layout) -> Option<String> {
    let plain = |n: &str| n.bytes().all(|b| (0x20..0x7f).contains(&b) && b != b'"' && b != b'\\');
    if !l.fields.iter().all(|f| plain(&f.name)) {
        return None;
    }
    let name = format!("lum_json_{k}");
    let max_value = |st: ir::Storage| match st {
        ir::Storage::Int32 => 11,
        ir::Storage::F64 => 32,
        ir::Storage::Bool => 5,
        ir::Storage::Value => 18,
    };
    // The room for the fields from `i` on, with JS values as short strings
    // (JS_JSONPutShortString, 18 characters), and the closing brace.
    let room = |i: usize| -> usize { l.fields[i..].iter().map(|f| f.name.len() + 4 + max_value(f.storage)).sum::<usize>() + 1 };
    writeln!(c, "static int {name}(JSContext *ctx, JSJSONWriter *w, const void *rec, int depth)\n{{").unwrap();
    c.push_str("    const LumStruct *s = rec;\n    const uint8_t *d = (const uint8_t *)s->data;\n");
    c.push_str("    uint8_t *p, *q;\n    int first = 1, r;\n    JSValue v;\n");
    c.push_str("    (void)first; (void)r; (void)v; (void)d; (void)q;\n");
    writeln!(c, "    if (!(p = JS_JSONRoom(w, {})))", 1 + room(0)).unwrap();
    c.push_str("        return lum_struct_json_from(ctx, w, s, depth, 0, 1);\n    *p++ = '{';\n");
    // Whether a field before is written for sure (then a key has its
    // comma), or may be (then `first` tells).
    let (mut certain, mut possible) = (false, false);
    for (i, f) in l.fields.iter().enumerate() {
        let off = f.offset;
        let key = format!(",\"{}\":", f.name);
        let put_key = |c: &mut String, indent: &str, certain: bool, possible: bool| {
            if certain {
                writeln!(c, "{indent}memcpy(p, {}, {}); p += {};", c_str(&key), key.len(), key.len()).unwrap();
            } else if !possible {
                writeln!(c, "{indent}memcpy(p, {}, {}); p += {};", c_str(&key[1..]), key.len() - 1, key.len() - 1)
                    .unwrap();
            } else {
                writeln!(
                    c,
                    "{indent}if (first) {{ memcpy(p, {}, {}); p += {}; }} else {{ memcpy(p, {}, {}); p += {}; }}",
                    c_str(&key[1..]),
                    key.len() - 1,
                    key.len() - 1,
                    c_str(&key),
                    key.len(),
                    key.len()
                )
                .unwrap();
            }
            writeln!(c, "{indent}first = 0;").unwrap();
        };
        let cond = if f.universal { None } else { Some(format!("s->mask & {}u", 1u32 << i)) };
        match f.storage {
            ir::Storage::Value => {
                writeln!(c, "    v = *(const JSValue *)(d + {off});").unwrap();
                match &cond {
                    Some(m) => writeln!(c, "    if (({m}) && lum_json_present(ctx, v)) {{").unwrap(),
                    None => c.push_str("    if (lum_json_present(ctx, v)) {\n"),
                }
                put_key(c, "        ", certain, possible);
                c.push_str("        if (JS_VALUE_GET_TAG(v) == JS_TAG_STRING && (q = JS_JSONPutShortString(p, v))) {\n");
                c.push_str("            p = q;\n        } else {\n");
                c.push_str("            JS_JSONCommit(w, p);\n            r = JS_JSONWriteValue(ctx, w, v, depth + 1);\n");
                c.push_str("            if (r <= 0)\n                return r;\n");
                writeln!(c, "            if (!(p = JS_JSONRoom(w, {})))", room(i + 1)).unwrap();
                writeln!(c, "                return lum_struct_json_from(ctx, w, s, depth, {}, 0);", i + 1).unwrap();
                c.push_str("        }\n    }\n");
                possible = true;
            }
            st => {
                let indent = if cond.is_some() { "        " } else { "    " };
                if let Some(m) = &cond {
                    writeln!(c, "    if ({m}) {{").unwrap();
                }
                put_key(c, indent, certain, possible);
                match st {
                    ir::Storage::Int32 => {
                        writeln!(c, "{indent}p = JS_JSONPutInt(p, *(const int32_t *)(d + {off}));").unwrap()
                    }
                    ir::Storage::F64 => {
                        writeln!(c, "{indent}p = JS_JSONPutDouble(p, *(const double *)(d + {off}));").unwrap()
                    }
                    _ => writeln!(
                        c,
                        "{indent}if (d[{off}]) {{ memcpy(p, \"true\", 4); p += 4; }} else {{ memcpy(p, \"false\", 5); p += 5; }}"
                    )
                    .unwrap(),
                }
                if cond.is_some() {
                    c.push_str("    }\n");
                    possible = true;
                } else {
                    certain = true;
                    possible = true;
                }
            }
        }
    }
    c.push_str("    *p++ = '}';\n    JS_JSONCommit(w, p);\n    return 1;\n}\n");
    Some(name)
}

/// The `aot type` layouts (`LumLayoutDesc`), and the literal strings
/// their fields may hold.
fn layouts(c: &mut String, m: &ir::Module, int_wrapping: bool) {
    let mut lits: Vec<String> = Vec::new();
    for (k, l) in m.layouts.iter().enumerate() {
        writeln!(c, "static const LumFieldDesc lum_fields_{k}[] = {{").unwrap();
        for f in &l.fields {
            let storage = match f.storage {
                ir::Storage::Int32 => 0,
                ir::Storage::F64 => 1,
                ir::Storage::Bool => 2,
                ir::Storage::Value => 3,
            };
            writeln!(c, "    {{ {}, {storage}, {}, {} }},", c_str(&f.name), f.simple as u8, f.offset).unwrap();
        }
        c.push_str("    { NULL, 0, 0, 0 },\n};\n");
        for (j, mem) in l.members.iter().enumerate() {
            writeln!(c, "static const LumTypeDesc lum_types_{k}_{j}[] = {{").unwrap();
            for t in &mem.types {
                let (kind, nlits, layout, base) = match t {
                    ir::FieldType::Absent => (0, 0, 0, 0),
                    ir::FieldType::Int => (1, 0, 0, 0),
                    ir::FieldType::Number => (2, 0, 0, 0),
                    ir::FieldType::Bool => (3, 0, 0, 0),
                    ir::FieldType::String => (4, 0, 0, 0),
                    ir::FieldType::Literals(ls) => {
                        let base = lits.len();
                        lits.extend(ls.iter().cloned());
                        (5, ls.len(), 0, base)
                    }
                    ir::FieldType::Struct(s) => (6, 0, *s, 0),
                    ir::FieldType::Array(s) => (7, 0, *s, 0),
                };
                writeln!(c, "    {{ {kind}, {nlits}, {layout}, {base} }},").unwrap();
            }
            c.push_str("    { 0, 0, 0, 0 },\n};\n");
        }
        writeln!(c, "static const LumMemberDesc lum_members_{k}[] = {{").unwrap();
        for (j, mem) in l.members.iter().enumerate() {
            writeln!(c, "    {{ {}u, lum_types_{k}_{j} }},", mem.mask).unwrap();
        }
        c.push_str("    { 0, NULL },\n};\n");
    }
    c.push_str("const LumLayoutDesc lum_layouts[] = {\n");
    for (k, l) in m.layouts.iter().enumerate() {
        writeln!(
            c,
            "    {{ {}, {}, {}, {}, {}, lum_fields_{k}, lum_members_{k} }},",
            c_str(&l.name),
            l.fields.len(),
            l.size,
            l.members.len(),
            (l.members.len() > 1) as u8
        )
        .unwrap();
    }
    c.push_str("    { NULL, 0, 0, 0, 0, NULL, NULL },\n};\n");
    writeln!(c, "const int32_t lum_nlayouts = {};", m.layouts.len()).unwrap();
    let mut writers = Vec::new();
    for (k, l) in m.layouts.iter().enumerate() {
        writers.push(json_writer(c, k, l));
    }
    c.push_str("JSJSONRecordFunc *const lum_layout_json[] = {\n");
    for w in &writers {
        writeln!(c, "    {},", w.as_deref().unwrap_or("NULL")).unwrap();
    }
    c.push_str("    NULL,\n};\n");
    c.push_str("const char *const lum_struct_lits[] = {\n");
    for s in &lits {
        writeln!(c, "    {},", c_str(s)).unwrap();
    }
    c.push_str("    NULL,\n};\n");
    writeln!(c, "const int32_t lum_nstruct_lits = {};", lits.len()).unwrap();
    writeln!(c, "int lum_int_wrapping = {};\n", int_wrapping as u8).unwrap();
}
